const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('../../backend/node_modules/@playwright/test');
const root = path.resolve(__dirname, '../..');
const source = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/^import .*;\r?\n/gm, '').replace(/export (async )?function/g, '$1function');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
    await page.route('http://localhost:3000/pending-check', route => route.fulfill({ contentType: 'text/html', body: `<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/@tabler/core@1.0.0-beta20/dist/css/tabler.min.css"><link rel="stylesheet" href="/assets/css/custom.css"><div id="app"></div>` }));
    await page.goto('http://localhost:3000/pending-check');
    await page.evaluate(() => {
      location.hash = '#/pos';
      window.watchDataChanges = () => () => {};
      window.fixture = { id: 'pending', estado: 'abierta', cierrePendiente: true, fecha: '2026-10-06', createdAt: '2026-10-06T13:00:00Z', usuarioApertura: { nombre: 'Cajero anterior' }, montoApertura: 100, totalVentasEfectivo: 50, totalVentasNequi: 0, totalVentasDaviplata: 0, totalVentasTarjeta: 0, totalVentasTransferencia: 0, totalEgresos: 20 };
      window.calls = [];
      window.apiFetch = async (url, opts = {}) => {
        if (opts.method === 'POST') { window.calls.push({ url, body: JSON.parse(opts.body) }); return { message: 'Cerrada' }; }
        if (url.startsWith('/caja/reporte')) return window.fixture;
        if (url === '/config/sedes') return [{ id: 'A', nombre: 'Sede A' }, { id: 'B', nombre: 'Sede B' }];
        if (url === '/config/sistema') return {};
        return [];
      };
      window.getUsuario = () => ({ rol: 'admin', sedeId: 'A', nombre: 'Administrador' });
      window.getLocalDateStr = () => '2026-10-07';
      window.initBarcodeScanner = () => {}; window.destroyBarcodeScanner = () => {};
      window.showToast = () => {};
      window.erpHeader = (o) => `<h1>${o.title}</h1>`; window.erpAction = () => '';
      window.printCierreTicket = () => {};
      window.bootstrap = { Modal: class { constructor(el) { this.el = el; } show() { this.el.style.display = 'block'; this.el.classList.add('show'); } hide() { this.el.style.display = 'none'; this.el.classList.remove('show'); } } };
    });
    await page.evaluate(async code => { await new Function(`${code}\nreturn initPos;`)()(document.getElementById('app')); }, source('frontend/assets/js/modules/pos.js'));
    assert.match(await page.locator('.pos-gate-card').innerText(), /cierre pendiente del día anterior/);
    assert.match(await page.locator('.pos-gate-card').innerText(), /2026-10-06/);
    assert.match(await page.locator('.pos-gate-card').innerText(), /Cajero anterior/);
    assert.equal(await page.locator('#pos-checkout-btn').count(), 0);
    assert.equal(await page.locator('.pos-session-chip--scan').count(), 0);
    assert.equal(await page.locator('.pos-gate-card a').getAttribute('href'), '#/caja?sede=A');
    await page.screenshot({ path: path.join(__dirname, 'cierre-pendiente-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(__dirname, 'cierre-pendiente-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1366, height: 900 });
    await page.evaluate(async code => { location.hash = '#/caja?sede=B'; await new Function(`${code}\nreturn initCaja;`)()(document.getElementById('app')); }, source('frontend/assets/js/modules/caja.js'));
    await page.waitForSelector('#btn-pos-liberar');
    assert.equal(await page.locator('#select-caja-sede').inputValue(), 'B');
    assert.equal(await page.locator('#btn-pos-egreso').isDisabled(), true);
    await page.locator('#btn-pos-liberar').click();
    assert.equal(await page.locator('#cierre-efectivo').inputValue(), '');
    assert.equal(await page.locator('#cierre-observaciones').getAttribute('required'), '');
    assert.match(await page.locator('#cierre-efectivo-esperado').innerText(), /130/);
    await page.locator('#btn-cierre-confirmar-efectivo').click();
    assert.equal(await page.locator('#cierre-efectivo').inputValue(), '130');
    assert.match(await page.locator('#cierre-efectivo-diferencia').innerText(), /coincide/);
    assert.equal(await page.evaluate(() => window.calls.length), 0);
    await page.locator('#btn-cierre-otro-efectivo').click();
    assert.equal(await page.locator('#cierre-efectivo').inputValue(), '');
    assert.equal(await page.locator('#cierre-efectivo').evaluate(el => el === document.activeElement), true);
    await page.locator('#cierre-efectivo').fill('140');
    assert.match(await page.locator('#cierre-efectivo-diferencia').innerText(), /Sobrante:.*10/);
    await page.locator('#cierre-efectivo').fill('120');
    assert.match(await page.locator('#cierre-efectivo-diferencia').innerText(), /Faltante:.*10/);
    await page.locator('#btn-cierre-confirmar-efectivo').click();
    await page.screenshot({ path: path.join(__dirname, 'cierre-administrativo.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(__dirname, 'cierre-rapido-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1366, height: 900 });
    await page.evaluate(() => { document.getElementById('modal-cierre').style.display = 'none'; });
    await page.locator('#btn-pos-cierre').click();
    assert.equal(await page.locator('#cierre-efectivo').inputValue(), '');
    await page.evaluate(() => { document.getElementById('modal-cierre').style.display = 'none'; });
    await page.locator('#btn-pos-liberar').click();
    await page.locator('#cierre-efectivo').fill('120');
    await page.locator('#cierre-observaciones').fill('Cierre olvidado');
    await page.locator('#form-cierre button[type=submit]').click();
    await page.waitForFunction(() => window.calls.length === 1);
    const call = await page.evaluate(() => window.calls[0]);
    assert.equal(call.url, '/caja/liberar');
    assert.equal(call.body.cajaId, 'pending');
    assert.equal(call.body.sedeId, 'B');
    assert.equal(call.body.totalVentasEfectivo, 120);
    assert.equal(call.body.observaciones, 'Cierre olvidado');
    console.log('OK: cierre rápido con monto esperado, ingreso manual con faltante/sobrante, reinicio al reabrir, móvil sin desborde y cierre administrativo con arqueo/motivo.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
